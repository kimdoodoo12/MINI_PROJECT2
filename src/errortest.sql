SELECT MENU_NAME, COUNT(*) 
    FROM CUSTOMERLOG C1 JOIN MENU M1 ON C1.MENU_ID = M1.MENU_ID 
    WHERE C1.CUSTOMERLOG_DAY = 3 AND C1.CUSTOMER_STATE = 'SERVED'
    GROUP BY M1.menu_id;

SELECT PRODUCT_NAME, SUM(-PRODUCT_QTY) AS USED
FROM PRODUCTLOG PL1 JOIN PRODUCT P1 ON PL1.PRODUCT_ID = P1.PRODUCT_NO
WHERE PL1.CUSTOMERLOG_DAY = 3 AND PL1.PRODUCT_CONDITION = '사용'
GROUP BY P1.PRODUCT_NAME;

SELECT PRODUCT_NAME, SUM(PRODUCT_QTY) AS REMAIN
FROM PRODUCTLOG PL1 JOIN PRODUCT P1 ON PL1.PRODUCT_ID = P1.PRODUCT_NO
GROUP BY P1.PRODUCT_NAME;

SELECT P.PRODUCT_NAME,
       SUM(-L.PRODUCT_QTY) AS TOTAL_USED,
       COUNT(DISTINCT L.CUSTOMERLOG_DAY) AS DAYS
FROM PRODUCTLOG L JOIN PRODUCT P ON L.PRODUCT_ID = P.PRODUCT_NO
WHERE L.PRODUCT_CONDITION = '사용'
GROUP BY P.PRODUCT_NAME;

